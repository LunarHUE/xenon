/**
 * Emits src/attrs.generated.ts from the WHATWG attribute index
 * (html-element-attributes) and the ARIA attribute list (aria-attributes),
 * narrowed by scripts/attrs.overrides.ts.
 *
 *   bun scripts/gen-attrs.ts          write the file
 *   bun scripts/gen-attrs.ts --check  exit 1 if the file is stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { ariaAttributes } from 'aria-attributes'
import { htmlElementAttributes } from 'html-element-attributes'

import { aria, booleans, enumerated, strings } from './attrs.overrides'

const OUT = new URL('../src/attrs.generated.ts', import.meta.url)

function union(values: readonly string[]): string {
  return values.map((v) => `'${v}'`).join(' | ')
}

function valueType(tag: string, name: string): string {
  if (booleans.has(name)) return 'boolean'
  if (strings.has(name)) return 'string'
  const own = enumerated[tag]?.[name] ?? enumerated['*']?.[name]
  return own ? union(own) : 'string | number'
}

function key(name: string): string {
  return /^[a-z][a-z0-9]*$/i.test(name) ? name : `'${name}'`
}

function lines(tag: string, names: readonly string[]): string {
  return names.map((name) => `  ${key(name)}?: ${valueType(tag, name)}`).join('\n')
}

const globals = [...new Set([...htmlElementAttributes['*']!, 'role'])].sort()
// `role` is in both lists; it is emitted once, with the globals.
const ariaLines = ariaAttributes
  .filter((name) => name !== 'role')
  .map((name) => `  '${name}'?: ${aria[name] ? union(aria[name]) : 'string'}`)
  .join('\n')

const tags = Object.keys(htmlElementAttributes)
  .filter((tag) => tag !== '*')
  .sort()

let out = `// Generated by scripts/gen-attrs.ts. Do not edit; run \`bun run gen\`.

/** Attributes valid on every element, plus ARIA and data-* hooks. */
export interface GlobalAttrs {
${lines('*', globals)}
${ariaLines}
  [data: \`data-\${string}\`]: string | number | boolean | undefined
}

/** Attributes specific to one tag. Tags with none are absent. */
export interface TagAttrs {
`
for (const tag of tags) {
  out += `  ${tag}: {\n${lines(tag, htmlElementAttributes[tag]!)
    .split('\n')
    .map((l) => `  ${l}`)
    .join('\n')}\n  }\n`
}
out += '}\n'

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    /* missing counts as stale */
  }
  if (current !== out) {
    console.error('src/attrs.generated.ts is stale. Run `bun run gen`.')
    process.exit(1)
  }
} else {
  writeFileSync(OUT, out)
}
